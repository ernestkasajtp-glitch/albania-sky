// Isolated low-seat task -> flight edit browser regression against the built UI.
// Every API request is answered by this local fixture server; no live backend,
// real credentials, database, or production mutations are involved.
import assert from "node:assert/strict";
import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { resolve, join, extname, sep } from "node:path";
import { once } from "node:events";
import { execFileSync } from "node:child_process";
import { chromium } from "../../api-server/node_modules/playwright-core/index.mjs";

if (process.env.NODE_ENV === "production" || process.env.REPLIT_DEPLOYMENT)
  throw new Error("Browser fixture must never run in production");

const root = resolve("dist/public");
const prefix = "/flight-system/";
const calls = [];
let flight = {
  id: 1, flightNumber: "FIX101", airline: "Fixture Air", fromCity: "Tirana",
  toCity: "Rome", departureDate: "2026-06-20T00:00:00.000Z", departureTime: "10:00",
  arrivalDate: "2026-06-20T00:00:00.000Z", arrivalTime: "12:00", totalSeats: 45,
  soldSeats: 40, adultPrice: 220, childPrice: 180, infantPrice: 50, status: "open",
};
const task = {
  id: 91001, title: "Low seats: Fixture Air FIX101", description: "Fixture task",
  status: "todo", priority: "high", assigneeId: null, creatorId: 951000,
  dueDate: null, completedAt: null, parentId: null, entityType: "flight", entityId: 1,
  labels: [], watchers: [], autoGenerated: true, autoRuleKey: "low_seats_10:1",
  position: 0, createdAt: "2026-01-01T00:00:00.000Z", updatedAt: "2026-01-01T00:00:00.000Z",
  entity: { type: "flight", id: 1, label: "FIX101", sublabel: "Tirana → Rome" },
};
function send(res, status, body, type = "application/json") {
  res.writeHead(status, { "Content-Type": type, "Cache-Control": "no-store" });
  res.end(type === "application/json" ? JSON.stringify(body) : body);
}
async function bodyOf(req) {
  let text = "";
  for await (const chunk of req) text += chunk;
  return text ? JSON.parse(text) : {};
}

const server = createServer(async (req, res) => {
  const url = new URL(req.url, "http://127.0.0.1");
  const path = url.pathname;
  if (path.startsWith("/api/")) {
    const body = req.method === "PATCH" || req.method === "POST" ? await bodyOf(req) : undefined;
    calls.push({ method: req.method, path, body });
    if (path === "/api/admin/has-admin") return send(res, 200, { exists: true });
    if (path === "/api/admin/me") return send(res, 200, {
      id: 951000, name: "Fixture Admin", email: "fixture-admin@local.test", role: "admin",
    });
    if (path === "/api/branding") return send(res, 200, {
      siteName: "Fixture FMS", tagline: "", logoBase64: null, backgroundBase64: null, primaryColor: "#3b82f6",
    });
    if (path === "/api/permissions/my") return send(res, 200, {});
    if (path === "/api/modules") return send(res, 200, { revision: 1, modules: [
      { id: "tasks", label: "Tasks", description: "Fixture tasks", paths: ["/tasks"], enabled: true, locked: false },
      { id: "flights", label: "Flights", description: "Fixture flights", paths: ["/flights"], enabled: true, locked: true },
    ] });
    if (path === "/api/tasks" && req.method === "GET") return send(res, 200, [task]);
    if (path === "/api/tasks-meta/users") return send(res, 200, []);
    if (path === "/api/tasks-stats") return send(res, 200, { mineOpen: 1, overdue: 0, unreadNotifs: 0 });
    if (path === "/api/tasks-entity-counts") return send(res, 200, {});
    if (path === "/api/flights/1" && req.method === "GET") return send(res, 200, flight);
    if (path === "/api/flights/1" && req.method === "PATCH") {
      flight = { ...flight, ...body };
      return send(res, 200, flight);
    }
    if (path === "/api/bookings" || path === "/api/booking-engine/agency-groups" ||
        path === "/api/agency-groups" || path === "/api/google-price-rules") return send(res, 200, []);
    if (path === "/api/live/events") return send(res, 204, "");
    return send(res, 200, []);
  }
  if (!path.startsWith(prefix)) return send(res, 404, "Not found", "text/plain");
  const relative = path.slice(prefix.length);
  const file = resolve(root, relative || "index.html");
  if (file !== root && !file.startsWith(root + sep)) return send(res, 403, "Forbidden", "text/plain");
  try {
    const bytes = await readFile(file);
    const mime = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css",
      ".svg": "image/svg+xml", ".png": "image/png", ".woff2": "font/woff2" };
    return send(res, 200, bytes, mime[extname(file)] || "application/octet-stream");
  } catch {
    if (!extname(file)) return send(res, 200, await readFile(join(root, "index.html")), "text/html");
    return send(res, 404, "Not found", "text/plain");
  }
});

let browser;
try {
  server.listen(0, "127.0.0.1");
  await once(server, "listening");
  const origin = `http://127.0.0.1:${server.address().port}`;
  browser = await chromium.launch({
    executablePath: process.env.CHROMIUM_PATH || execFileSync("which", ["chromium"], { encoding: "utf8" }).trim(),
    headless: true, args: ["--no-sandbox"],
  });
  const context = await browser.newContext({ serviceWorkers: "block", viewport: { width: 1280, height: 900 } });
  await context.route("**/*", route =>
    new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
  const page = await context.newPage();
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));

  // Direct flight route must not open edit automatically.
  await page.goto(`${origin}${prefix}flights/1`);
  await page.getByText("Fluturimi nuk u gjet").waitFor({ state: "hidden", timeout: 1000 }).catch(() => {});
  console.log("DIRECT BODY", (await page.locator("body").innerText()).slice(0, 1400));
  await page.getByRole("heading", { name: /Flight/ }).waitFor();
  assert.equal(await page.getByRole("dialog").count(), 0, "Flight without edit query must not auto-open editor");

  // Task entity chip must route to the edit URL and open a prefilled editor.
  await page.goto(`${origin}${prefix}tasks`);
  await page.getByText("Low seats: Fixture Air FIX101", { exact: true }).waitFor();
  await page.getByRole("link", { name: "FIX101" }).click();
  await page.waitForURL("**/flight-system/flights/1?edit=1");
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("heading", { name: "Ndrysho Fluturimin" }).waitFor();
  const seats = dialog.locator('input[type="number"]').nth(0);
  const adultPrice = dialog.locator('input[type="number"]').nth(1);
  assert.equal(await seats.inputValue(), "45", "Editor should prefill the flight's seat count");
  assert.equal(await adultPrice.inputValue(), "220", "Editor should prefill the flight's adult price");
  await page.screenshot({ path: "/tmp/low-seat-flight-edit.png", fullPage: true });

  await seats.fill("52");
  await dialog.getByRole("button", { name: "Ruaj", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  const patch = calls.find(call => call.method === "PATCH");
  assert.ok(patch, "Expected a mocked flight PATCH");
  assert.equal(patch.path, "/api/flights/1", "Save must target root /api, not /flight-system/api");
  assert.equal(calls.some(call => call.path.startsWith("/flight-system/api/")), false,
    "No API request may be sent below the static app prefix");
  assert.deepEqual(patch.body, { totalSeats: 52, adultPrice: 220, childPrice: 180, infantPrice: 50 });
  assert.equal(flight.totalSeats, 52);
  assert.deepEqual(errors, [], "No uncaught frontend errors");
  await context.close();
  console.log("Low-seat task → flight edit browser regression passed.", JSON.stringify({
    url: page.url(), patch, screenshot: "/tmp/low-seat-flight-edit.png", apiCalls: calls.length,
  }));
} finally {
  if (browser) await browser.close();
  server.close();
  await once(server, "close");
}
