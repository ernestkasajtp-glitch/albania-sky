// ── Task Row ────────────────────────────────────────────────────────────────
function TaskRow({ t, users, onOpen, selectable, selected, onToggleSelect }: {
  t: Task; users: StaffUser[]; onOpen: (id: number) => void;
  selectable?: boolean; selected?: boolean; onToggleSelect?: (id: number) => void;
}) {
  const [, setLocation] = useLocation();
  const sm = STATUS_META[t.status];
  const pm = PRIORITY_META[t.priority];
  const due = fmtDue(t.dueDate);
  const assignee = users.find(u => u.id === t.assigneeId);
  const isDone = t.status === "done" || t.status === "cancelled";

  return (
    <div className={cn("w-full group flex items-center gap-3 px-3 py-2.5 border-b border-slate-100 hover:bg-slate-50",
      selected && "bg-blue-50/70 hover:bg-blue-50")}>
      {selectable && (
        <Checkbox checked={!!selected} onCheckedChange={() => onToggleSelect?.(t.id)} aria-label="Zgjidh detyrën" className="shrink-0" />
      )}
      <button onClick={() => onOpen(t.id)} className="flex-1 min-w-0 flex items-center gap-3 text-left">
        <div className={cn("w-5 h-5 rounded-full flex items-center justify-center shrink-0", sm.bg)}>
          <sm.icon className={cn("w-3.5 h-3.5", sm.color)} />
        </div>
        <pm.icon className={cn("w-4 h-4 shrink-0", pm.color)} />
        <span className={cn("flex-1 min-w-0 truncate text-sm", isDone ? "text-slate-400 line-through" : "text-slate-900 font-medium")}>
          {t.title}
        </span>
        {t.entity && (
          <span
            role="link"
            tabIndex={0}
            onClick={(e) => { e.stopPropagation(); setLocation(taskEntityLink(t)); }}
            onKeyDown={(e) => { if (e.key === "Enter") { e.stopPropagation(); setLocation(taskEntityLink(t)); } }}
            className="hidden md:inline-flex items-center gap-1 px-1.5 py-0.5 rounded bg-indigo-50 hover:bg-indigo-100 text-indigo-700 text-[10px] font-bold border border-indigo-200 cursor-pointer transition-colors"
            title={`Hap ${t.entity.type} ${t.entity.label}`}
          >
            <Link2 className="w-3 h-3" /> {t.entity.label}
          </span>
        )}
        {t.labels.slice(0, 3).map(l => (
          <span key={l} className="hidden sm:inline-flex items-center px-1.5 py-0.5 rounded bg-slate-100 text-slate-600 text-[10px] font-semibold">{l}</span>
        ))}
        {t.dueDate && (
          <span className={cn("text-[11px] font-semibold tabular-nums px-1.5 py-0.5 rounded shrink-0",
            due.tone === "overdue" ? "bg-rose-100 text-rose-700" :
            due.tone === "soon" ? "bg-amber-100 text-amber-800" : "bg-slate-100 text-slate-600")}>
            <Calendar className="w-3 h-3 inline mr-0.5" />{due.text}
          </span>
        )}
        {assignee ? (
          <div className="w-6 h-6 rounded-full bg-gradient-to-br from-blue-500 to-indigo-600 text-white text-[10px] font-bold flex items-center justify-center shrink-0" title={assignee.name}>
            {assignee.name.split(" ").map(w => w[0]).join("").slice(0,2).toUpperCase()}
          </div>
        ) : (
          <div className="w-6 h-6 rounded-full border-2 border-dashed border-slate-300 flex items-center justify-center shrink-0" title="Pa caktuar">
            <UserIcon className="w-3 h-3 text-slate-400" />
          </div>
        )}
      </button>
    </div>
  );
}

