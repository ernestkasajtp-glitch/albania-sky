const ENTITY_LINK: Record<EntityType, (id: number) => string> = {
  booking: (id) => `/bookings/${id}`,
  agent: (id) => `/agents/${id}`,
  flight: (id) => `/flights/${id}`,
  group_ticket: () => `/group-tickets`,
};

function taskEntityLink(task: Task): string {
  const entity = task.entity!;
  const url = ENTITY_LINK[entity.type](entity.id);
  return entity.type === "flight" && task.autoRuleKey?.startsWith("low_seats_10:")
    ? `${url}?edit=1` : url;
}

function fmtDue(iso: string | null): { text: string; tone: "neutral" | "soon" | "overdue" } {
  if (!iso) return { text: "Pa afat", tone: "neutral" };
  const d = new Date(iso);
  const now = new Date();
  const diffMs = d.getTime() - now.getTime();
  const diffDays = Math.round(diffMs / (1000 * 60 * 60 * 24));
  if (diffMs < 0) return { text: `Vonesë ${Math.abs(diffDays)} ditë`, tone: "overdue" };
  if (diffDays === 0) return { text: "Sot", tone: "soon" };
  if (diffDays === 1) return { text: "Nesër", tone: "soon" };
  if (diffDays < 7) return { text: `Në ${diffDays} ditë`, tone: "soon" };
  return { text: d.toLocaleDateString("sq-AL", { day: "2-digit", month: "short" }), tone: "neutral" };
}

function relTime(iso: string): string {
  const d = new Date(iso);
  const s = Math.floor((Date.now() - d.getTime()) / 1000);
  if (s < 60) return `${s}s më parë`;
  if (s < 3600) return `${Math.floor(s / 60)}min më parë`;
  if (s < 86400) return `${Math.floor(s / 3600)}h më parë`;
  if (s < 604800) return `${Math.floor(s / 86400)}d më parë`;
  return d.toLocaleDateString("sq-AL");
}

