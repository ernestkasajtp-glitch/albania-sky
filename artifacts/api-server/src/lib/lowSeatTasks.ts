import { db, bookingUsersTable, flightsTable, tasksTable, taskNotificationsTable, taskActivityTable } from "@workspace/db";
import { eq, inArray, asc, sql } from "drizzle-orm";
import { isModuleEnabled } from "./moduleControls.js";
import { notifyDataChanged } from "./liveEvents.js";
import { logger } from "./logger.js";

let running = false;
let timer: ReturnType<typeof setInterval> | undefined;

/** Small durable outbox drain: row locks protect simultaneous workers/restarts.
 * Task + notifications + processed marker commit together; failed runs retry.
 */
export async function processLowSeatTasks(client = db, enabled = isModuleEnabled, notify = notifyDataChanged): Promise<void> {
  if (running) return;
  running = true;
  try {
    if (!(await enabled("tasks"))) return;
    for (let i = 0; i < 50; i++) {
      const created = await client.transaction(async tx => {
        const result = await tx.execute(sql`
          SELECT id, flight_id, before_available, after_available, cause, created_at
          FROM flight_low_seat_events WHERE processed_at IS NULL
          ORDER BY id LIMIT 1 FOR UPDATE SKIP LOCKED
        `);
        const event = result.rows[0] as {
          id: string; flight_id: number; before_available: number; after_available: number;
          cause: string; created_at: Date;
        } | undefined;
        if (!event) return false;
        const staff = await tx.select({ id: bookingUsersTable.id, role: bookingUsersTable.role })
          .from(bookingUsersTable).where(inArray(bookingUsersTable.role, ["admin", "manager"]))
          .orderBy(asc(bookingUsersTable.id));
        const adminId = staff.find(u => u.role === "admin")?.id;
        const managerId = staff.find(u => u.role === "manager")?.id;
        const creatorId = adminId ?? managerId;
        if (creatorId == null) return false; // Retain event until an owner exists.
        const [flight] = await tx.select({
          flightNumber: flightsTable.flightNumber, fromCity: flightsTable.fromCity,
          toCity: flightsTable.toCity, departureDate: flightsTable.departureDate,
        }).from(flightsTable).where(eq(flightsTable.id, event.flight_id));
        if (!flight) return false;
        const watchers = [...new Set([adminId, managerId].filter((id): id is number => id != null))];
        const label = `${flight.flightNumber} · ${flight.fromCity} → ${flight.toCity} · ${flight.departureDate}`;
        const cause = event.cause === "reduction" ? "ulja e vendeve"
          : event.cause === "sale_and_reduction" ? "shitja dhe ulja e vendeve" : "shitja";
        const [task] = await tx.insert(tasksTable).values({
          title: `Vende të lira ≤10: ${label}`,
          description: `Vendet e lira ranë nga ${event.before_available} në ${event.after_available} nga ${cause}.\n\nKlikoni fluturimin e lidhur për të hapur editimin. Ky njoftim nuk ndryshon çmimin apo gjendjen e fluturimit.`,
          status: "todo", priority: "high", creatorId, assigneeId: managerId ?? adminId!,
          entityType: "flight", entityId: event.flight_id,
          labels: ["Vende ≤10"], watchers, autoGenerated: true,
          autoRuleKey: `low_seats_10:${event.id}`,
        }).returning({ id: tasksTable.id });
        await tx.insert(taskActivityTable).values({
          taskId: task.id, userName: "Sistemi", action: "created",
          meta: { source: "low_seats_10", before: event.before_available, after: event.after_available },
        });
        await tx.insert(taskNotificationsTable).values(watchers.map(userId => ({
          userId, taskId: task.id, type: "assigned",
          title: `Vende të lira: ${event.after_available}`, body: label,
        })));
        await tx.execute(sql`UPDATE flight_low_seat_events SET processed_at = now(), task_id = ${task.id} WHERE id = ${event.id}`);
        return true;
      });
      if (!created) break;
      notify("tasks");
    }
  } catch (err) {
    logger.error({ err }, "Low-seat task creation failed; pending events retained for retry");
  } finally { running = false; }
}

export function startLowSeatTaskScheduler(): void {
  if (timer) return;
  void processLowSeatTasks();
  timer = setInterval(() => void processLowSeatTasks(), 15_000);
  timer.unref();
}
