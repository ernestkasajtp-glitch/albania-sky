import { pgTable, serial, integer, text, timestamp, jsonb, boolean, index } from "drizzle-orm/pg-core";

export const tasksTable = pgTable("tasks", {
  id: serial("id").primaryKey(),
  title: text("title").notNull(),
  description: text("description"),
  status: text("status").notNull().default("todo"),
  priority: text("priority").notNull().default("medium"),
  assigneeId: integer("assignee_id"),
  creatorId: integer("creator_id").notNull(),
  dueDate: timestamp("due_date", { withTimezone: true }),
  completedAt: timestamp("completed_at", { withTimezone: true }),
  parentId: integer("parent_id"),
  entityType: text("entity_type"),
  entityId: integer("entity_id"),
  labels: jsonb("labels").$type<string[]>().notNull().default([]),
  watchers: jsonb("watchers").$type<number[]>().notNull().default([]),
  autoGenerated: boolean("auto_generated").notNull().default(false),
  autoRuleKey: text("auto_rule_key"),
  position: integer("position").notNull().default(0),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow().$onUpdate(() => new Date()),
}, (t) => ({
  statusIdx: index("tasks_status_idx").on(t.status),
  assigneeIdx: index("tasks_assignee_idx").on(t.assigneeId),
  entityIdx: index("tasks_entity_idx").on(t.entityType, t.entityId),
  dueIdx: index("tasks_due_idx").on(t.dueDate),
}));

export const taskCommentsTable = pgTable("task_comments", {
  id: serial("id").primaryKey(),
  taskId: integer("task_id").notNull().references(() => tasksTable.id, { onDelete: "cascade" }),
  authorId: integer("author_id").notNull(),
  authorName: text("author_name").notNull(),
  body: text("body").notNull(),
  mentions: jsonb("mentions").$type<number[]>().notNull().default([]),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
}, (t) => ({ taskIdx: index("task_comments_task_idx").on(t.taskId) }));

export const taskActivityTable = pgTable("task_activity", {
  id: serial("id").primaryKey(),
  taskId: integer("task_id").notNull().references(() => tasksTable.id, { onDelete: "cascade" }),
  userId: integer("user_id"),
  userName: text("user_name"),
  action: text("action").notNull(),
  meta: jsonb("meta").$type<Record<string, any>>().notNull().default({}),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
}, (t) => ({ taskIdx: index("task_activity_task_idx").on(t.taskId) }));

export const taskLabelsTable = pgTable("task_labels", {
  id: serial("id").primaryKey(),
  name: text("name").notNull().unique(),
  color: text("color").notNull().default("#64748b"),
  description: text("description"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export const taskNotificationsTable = pgTable("task_notifications", {
  id: serial("id").primaryKey(),
  userId: integer("user_id").notNull(),
  taskId: integer("task_id").references(() => tasksTable.id, { onDelete: "cascade" }),
  type: text("type").notNull(),
  title: text("title").notNull(),
  body: text("body"),
  readAt: timestamp("read_at", { withTimezone: true }),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
}, (t) => ({ userIdx: index("task_notifications_user_idx").on(t.userId, t.readAt) }));

export type Task = typeof tasksTable.$inferSelect;
export type TaskComment = typeof taskCommentsTable.$inferSelect;
export type TaskActivity = typeof taskActivityTable.$inferSelect;
export type TaskLabel = typeof taskLabelsTable.$inferSelect;
export type TaskNotification = typeof taskNotificationsTable.$inferSelect;
